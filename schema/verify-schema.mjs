import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const sql = fs.readFileSync(path.join(dir, 'pozoverde_pg.sql'), 'utf8');

test('MonteReal PostgreSQL schema defines unique tables in valid FK dependency order', () => {
  const matches = [...sql.matchAll(/CREATE TABLE IF NOT EXISTS public\.([a-z_]+)/gi)].map(m => m[1]);
  assert.deepEqual(matches, ['tbl_tipo_empleado', 'tbl_empleados', 'usuario']);
  assert.ok(sql.includes('GENERATED BY DEFAULT AS IDENTITY'));
  assert.ok(sql.includes('password_hash'));
  assert.ok(!sql.includes('kword'));
});
