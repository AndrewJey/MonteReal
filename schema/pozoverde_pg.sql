-- Esquema PostgreSQL 17/18 corregido e idempotente para MonteReal Pozo Verde
-- Basado en monterealpozoverde1/.../pozoverde3.sql (elimina duplicado de tbl_tipo_empleado,
-- añade tbl_empleados referenciada por FK y usa IDENTITY en lugar de secuencias inexistentes).

CREATE TABLE IF NOT EXISTS public.tbl_tipo_empleado (
    id_tipo_empleado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion      TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.tbl_empleados (
    id_empleado      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula           VARCHAR(30) NOT NULL UNIQUE,
    nombre           VARCHAR(120) NOT NULL,
    apellidos        VARCHAR(120) NOT NULL,
    telefono         VARCHAR(30),
    correo           VARCHAR(120),
    activo           BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.usuario (
    id_usuario       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario          VARCHAR(50) NOT NULL UNIQUE,
    password_hash    TEXT NOT NULL,
    id_empleado      BIGINT NOT NULL REFERENCES public.tbl_empleados (id_empleado) ON UPDATE RESTRICT ON DELETE RESTRICT,
    id_tipo_empleado INTEGER NOT NULL REFERENCES public.tbl_tipo_empleado (id_tipo_empleado) ON UPDATE RESTRICT ON DELETE RESTRICT,
    creado_en        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO public.tbl_tipo_empleado (descripcion)
